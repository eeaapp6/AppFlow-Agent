def render_physical_properties(parameters: dict[str, Any]) -> str:
    nu = _param(parameters, "nu", "viscosity", "kinematic_viscosity", default="0.01")
    return _openfoam_header("dictionary", "physicalProperties") + f"""
nu              [0 2 -1 0 0 0 0] {nu};
"""


def render_u(parameters: dict[str, Any]) -> str:
    lid_velocity = _param(parameters, "lid_velocity", "top_velocity", "velocity", default="1")
    return _openfoam_header("volVectorField", "U") + f"""
dimensions      [0 1 -1 0 0 0 0];

internalField   uniform (0 0 0);

boundaryField
{{
    movingWall
    {{
        type            fixedValue;
        value           uniform ({lid_velocity} 0 0);
    }}

    fixedWalls
    {{
        type            noSlip;
    }}

    frontAndBack
    {{
        type            empty;
    }}
}}
"""


def render_p() -> str:
    return _openfoam_header("volScalarField", "p") + """
dimensions      [0 2 -2 0 0 0 0];

internalField   uniform 0;

boundaryField
{
    movingWall
    {
        type            zeroGradient;
    }

    fixedWalls
    {
        type            zeroGradient;
    }

    frontAndBack
    {
        type            empty;
    }
}
"""


def render_case_files(parameters: dict[str, Any]) -> list[tuple[PlannedFile, str]]:
    return [
        (PlannedFile("control", "case/system/controlDict", "openfoam-dict"), render_control_dict(parameters)),
        (PlannedFile("numerics", "case/system/fvSchemes", "openfoam-dict"), render_fv_schemes()),
        (PlannedFile("linear_solver", "case/system/fvSolution", "openfoam-dict"), render_fv_solution()),
        (PlannedFile("mesh", "case/system/blockMeshDict", "openfoam-dict"), render_block_mesh_dict()),
        (PlannedFile("physical_properties", "case/constant/physicalProperties", "openfoam-dict"), render_physical_properties(parameters)),
        (PlannedFile("initial_condition", "case/0/U", "openfoam-dict"), render_u(parameters)),
        (PlannedFile("initial_condition", "case/0/p", "openfoam-dict"), render_p()),
    ]
