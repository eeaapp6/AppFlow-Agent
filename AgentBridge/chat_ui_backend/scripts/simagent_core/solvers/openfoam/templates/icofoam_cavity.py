from typing import Any

from ....models import PlannedFile


def _param(parameters: dict[str, Any], *names: str, default: str) -> str:
    for name in names:
        value = parameters.get(name)
        if value is not None and str(value).strip():
            return str(value).strip()
    return default


def _openfoam_header(class_name: str, object_name: str) -> str:
    return f"""/*--------------------------------*- C++ -*----------------------------------*\\
| =========                 |                                                 |
| \\\\      /  F ield         | OpenFOAM: The Open Source CFD Toolbox           |
|  \\\\    /   O peration     | Generated by SimAgent                           |
|   \\\\  /    A nd           |                                                 |
|    \\\\/     M anipulation  |                                                 |
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       {class_name};
    object      {object_name};
}}
"""


def render_control_dict(parameters: dict[str, Any]) -> str:
    end_time = _param(parameters, "end_time", "endTime", "final_time", "finalTime", default="0.5")
    delta_t = _param(parameters, "delta_t", "deltaT", "time_step", "timestep", default="0.005")
    write_interval = _param(parameters, "write_interval", "writeInterval", default="20")
    return _openfoam_header("dictionary", "controlDict") + f"""
application     icoFoam;

startFrom       startTime;
startTime       0;
stopAt          endTime;
endTime         {end_time};
deltaT          {delta_t};

writeControl    timeStep;
writeInterval   {write_interval};
purgeWrite      0;

writeFormat     ascii;
writePrecision  6;
writeCompression off;

timeFormat      general;
timePrecision   6;

runTimeModifiable true;
"""


def render_fv_schemes() -> str:
    return _openfoam_header("dictionary", "fvSchemes") + """
ddtSchemes
{
    default         Euler;
}

gradSchemes
{
    default         Gauss linear;
}

divSchemes
{
    default         none;
    div(phi,U)      Gauss linear;
}

laplacianSchemes
{
    default         Gauss linear orthogonal;
}

interpolationSchemes
{
    default         linear;
}

snGradSchemes
{
    default         orthogonal;
}
"""


def render_fv_solution() -> str:
    return _openfoam_header("dictionary", "fvSolution") + """
solvers
{
    p
    {
        solver          PCG;
        preconditioner  DIC;
        tolerance       1e-06;
        relTol          0.05;
    }

    pFinal
    {
        $p;
        relTol          0;
    }

    U
    {
        solver          smoothSolver;
        smoother        symGaussSeidel;
        tolerance       1e-05;
        relTol          0;
    }
}

PISO
{
    nCorrectors     2;
    nNonOrthogonalCorrectors 0;
    pRefCell        0;
    pRefValue       0;
}
"""


